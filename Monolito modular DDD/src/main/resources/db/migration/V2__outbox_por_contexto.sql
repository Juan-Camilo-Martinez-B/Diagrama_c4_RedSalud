-- Outbox transaccional: una tabla por contexto que publica eventos, en su propio esquema.
-- secuencia conserva el orden de registro (y por lo tanto el orden por agregado).
-- publicado_en nulo = pendiente de relevar al bus.

CREATE TABLE agenda.outbox (
    secuencia     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id     UUID                     NOT NULL UNIQUE,
    contexto      VARCHAR(50)              NOT NULL,
    agregado_id   VARCHAR(200)             NOT NULL,
    tipo          VARCHAR(100)             NOT NULL,
    payload       VARCHAR(100000)          NOT NULL,
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    publicado_en  TIMESTAMP WITH TIME ZONE
);

