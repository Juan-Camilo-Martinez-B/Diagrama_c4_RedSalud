-- Outbox transaccional por contexto (mismo esquema y transaccion que el agregado) e inbox por
-- consumidor (deduplica eventos entregados al menos una vez).

CREATE TABLE identity.outbox (
    sequence     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     UUID                     NOT NULL UNIQUE,
    context      VARCHAR(50)              NOT NULL,
    aggregate_id VARCHAR(200)             NOT NULL,
    type         VARCHAR(100)             NOT NULL,
    payload      TEXT                     NOT NULL,
    recorded_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE
);

